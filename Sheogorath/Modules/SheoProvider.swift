import Foundation

struct SheoProvider: Sendable {
    // оставлю идею пока не забыл;
    //
    // SheoProvider — будущий модуль подключения внешних LLM-провайдеров.
    // Локальная GGUF-модель Sheogorath через этот файл НЕ работает:
    // она обслуживается собственным локальным inference engine внутри приложения.
    //
    // Назначение SheoProvider в будущем:
    // - подключение ChatGPT и других внешних LLM;
    // - единый интерфейс к разным внешним провайдерам;
    // - выбор внешнего провайдера и модели;
    // - формирование запросов в формате конкретного провайдера;
    // - получение обычных и streaming-ответов;
    // - преобразование внешнего ответа в внутренний формат Sheogorath;
    // - обработка сетевых ошибок, отмены и таймаутов;
    // - передача авторизационных данных без сохранения секретов в логах;
    // - сбор только технических метрик без содержимого чатов по умолчанию.
    //
    // Ограничения:
    // - этот модуль не читает файлы и другие данные самостоятельно;
    // - этот модуль не решает, какой контекст отправлять наружу;
    // - этот модуль не хранит историю чатов;
    // - этот модуль не содержит UI;
    // - наружу отправляются только данные, явно переданные Core;
}
